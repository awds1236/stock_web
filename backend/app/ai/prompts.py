"""AI 분석 프롬프트.

이 파일의 설계 목표는 둘입니다.

  1. **모델이 숫자를 지어내지 못하게 하는 것.** 실적·뉴스·목표주가를 묻지 않고,
     `app/reports.py` 가 계산한 숫자만 JSON 으로 넘긴 뒤 그 안에서만 서술하게
     합니다. 이건 신중함이 아니라 정확성의 문제입니다 -- 지어낸 숫자로 주문을
     넣으면 그 손실은 진짜입니다. 모델의 지식 시점(cutoff)은 알 수 없고
     데이터는 오늘 것이므로, 기억에 의존한 서술은 그 자체로 틀릴 위험이 큽니다.

  2. **판단을 내리게 하는 것.** 이 앱은 사용자가 실제 주문을 넣는 데 씁니다.
     "~일 수도 있습니다"로 끝나는 서술은 읽는 데 시간만 쓰고 아무것도 바꾸지
     않습니다. 그래서 스탠스를 명시하게 하고, 목표와 무효화 조건을 숫자로
     대게 합니다.

     한때 이 파일은 "매수/매도/보유 추천을 하지 마십시오"를 절대 규칙으로
     두었습니다. 그 결과는 안전이 아니라 **쓸모없음**이었습니다 -- 사용자는
     결국 스스로 판단하되 근거는 더 적게 가진 채로 판단하게 됩니다.

  3. 출력 형식은 여전히 고정합니다. 마지막 두 절은 '이 판단이 틀리는 경우'와
     '데이터 신뢰도'입니다. 강세 서술만 남으면 무효화 조건을 안 보게 되고,
     무효화 조건 없는 계획은 손절 없는 매매가 됩니다.
"""

from __future__ import annotations

import json
from typing import Any

SYSTEM = """당신은 한국어로 답하는 주식 매매 분석 보조자입니다. 사용자는 이
분석을 읽고 **실제 주문을 넣습니다.** 애매하게 쓰지 말고 판단을 내리십시오.

절대 규칙:
1. 숫자는 제공된 JSON 에 있는 것만 쓰십시오. 실적, 뉴스, 공시, 목표주가,
   경쟁사 정보는 이 데이터에 없습니다 -- 지어내지 말고 "이 앱의 데이터에는
   없습니다"라고 쓰십시오. 지어낸 숫자로 넣은 주문의 손실은 진짜입니다.
2. **판단을 내리십시오.** 스탠스(적극 매수 / 분할 매수 / 관망 / 회피)를
   하나 고르고 이유를 숫자로 대십시오. "~일 수도 있습니다"로 끝내지 마십시오.
3. 가격 목표와 손절 기준은 데이터의 지지/저항·분할 구간(`ladder`)에서만
   가져오십시오. 그 밖의 숫자를 목표로 제시하지 마십시오. "내일 X원" 같은
   시점 예측은 이 데이터로 계산되지 않으므로 쓰지 마십시오 -- 조건과 가격대로
   쓰십시오("저항 X 를 종가로 넘기면 다음 저항은 Y").
4. 데이터 품질이 나쁘면 **그 사실 자체가 판단입니다.** 예측의 skill score 가
   0 이하면 그 확률은 근거로 쓸 수 없다고 명시하고 판단에서 빼십시오.
   n_days 가 짧으면 장기 지표가 비어 있다는 뜻이므로 그렇게 쓰십시오.
5. null 은 "측정 불가"입니다. 반올림은 허용되나 없는 값을 추정하지 마십시오.
6. 기술적 지표의 성격을 알고 쓰십시오. 지지/저항은 뚫리면 의미가 반전되고
   이동평균 교차는 후행합니다 -- 그래서 무효화 가격이 판단의 일부입니다.

출력은 마크다운이며, 마지막 두 절은 반드시 다음이어야 합니다:
## 이 판단이 틀리는 경우
## 데이터 신뢰도
"""

_COMMON_TAIL = """
분량은 400~700자 정도로 압축하십시오. 표는 쓰지 말고 짧은 문단과 불릿으로
쓰십시오. 데이터의 caveats 배열이 판단을 흔드는 내용이면 '데이터 신뢰도' 절에
그렇게 쓰십시오.
"""

# 종목 분석에는 회차별 서술이 들어가므로 위 분량으로는 눌립니다. 분량을 강하게
# 줄이면 모델은 가장 긴 절(분할 구간)부터 잘라내고, 그러면 요구한 3회차가
# 사라집니다.
_STOCK_TAIL = """
분량은 900~1,400자 정도로 쓰십시오. 표는 쓰지 말고 짧은 문단과 불릿으로
쓰십시오. 판단과 숫자를 앞에 두고, 조건·한계는 뒤 두 절로 몰아 쓰십시오.
"""


def stock_prompt(report: dict[str, Any], forecast: dict | None = None) -> str:
    label = report.get("name") or report.get("ticker")
    body = {"stock": report}
    if forecast:
        body["forecast"] = forecast
    return f"""아래는 {report.get("market")} 시장 종목 **{label}
({report.get("ticker")})** 의 계산된 지표입니다.

다음 절 구성으로 서술하십시오:
## 판단
스탠스(적극 매수 / 분할 매수 / 관망 / 회피) 하나를 **첫 줄에** 쓰고, 그 근거를
숫자 3개 이내로 대십시오. 이어서 이 계획의 손익비(`ladder.risk` 의 `rr`)와
1주당 리스크(`risk_per_share`)를 한 줄로 적으십시오. 손익비가 1 미만이면
그 사실을 근거로 스탠스를 낮추십시오.
## 지금 상태
추세·모멘텀·변동성·상대강도를 숫자와 함께. 유니버스·업종 대비 어디에 있는지.
## 분할 대응 구간
데이터의 `ladder` 를 **그대로** 읽어 서술하십시오. 규칙:
- 매수 구간과 매도 구간을 **각각 최소 3회차**까지 회차별로 쓰십시오.
  회차마다 가격, 현재가 대비 거리, 비중, 그 회차까지 채웠을 때의 누적
  평균단가를 함께 적습니다. 숫자는 `ladder` 에 있는 값을 쓰고 직접
  계산하지 마십시오.
- 각 회차의 근거를 밝히십시오. `basis` 가 `level` 이면 지지/저항 클러스터
  (터치 `touches` 회)이고, `volatility` 면 **지지선이 모자라 ATR 등간격으로
  채운 구간**입니다 -- 후자는 반드시 그렇게 명시하십시오. 없는 지지선을
  있는 것처럼 쓰면 사용자가 그 가격에 실제로 주문을 넣습니다.
- `invalidation` 을 손절 기준으로 명시하십시오.
비중 방식은 `equal`(균등) 기준으로 서술하되, `pyramid`(뒤가중 -- 매수는 더 싼
회차, 매도는 더 비싼 회차에 더 싣는 방식)와 평균단가·손익비가 어떻게 달라지는지
한 줄로 비교하고, 이 종목에서는 어느 쪽이 나은지 숫자를 근거로 고르십시오.
## 이 판단이 틀리는 경우
어떤 수치가 어떻게 바뀌면 위 스탠스를 접어야 하는지. 무효화 가격, 반대 방향의
근거, 놓치고 있는 것. 조건문으로.
## 데이터 신뢰도
이 판단을 얼마나 믿을 수 있는지. 데이터 길이, 예측 품질(skill score), 지지/저항의
성격상 한계 중 **판단을 실제로 흔드는 것만** 쓰십시오. 일반론은 쓰지 마십시오.
{_STOCK_TAIL}
데이터:
```json
{_dump(body)}
```"""


def sector_prompt(report: dict[str, Any]) -> str:
    return f"""아래는 {report.get("market")} 시장 **{report.get("sector")}** 업종의
계산된 집계입니다.

다음 절 구성으로 서술하십시오:
## 판단
이 업종에 지금 비중을 둘지(적극 / 선별 / 관망 / 회피) 한 줄로 고르고 근거를
숫자로 대십시오.
## 업종 현황
수익률·상대강도·breadth 를 함께 읽어 서술. breadth 가 0.5 미만이면 소수 종목이
끌어올린 것이므로 반드시 그렇게 쓰십시오.
## 업종 내부 분화
leaders 와 laggards 의 격차가 무엇을 뜻하는지.
## 지켜볼 지점
업종 안에서 어떤 종목군을 먼저 볼지, 무엇이 확인되면 비중을 늘릴지.
## 이 판단이 틀리는 경우
## 데이터 신뢰도
{_COMMON_TAIL}
데이터:
```json
{_dump(report)}
```"""


def market_prompt(report: dict[str, Any]) -> str:
    market_kr = "한국" if report.get("market") == "KR" else "미국"
    return f"""아래는 **{market_kr} 시장** 전체(수집된 유니버스 동일가중)의 계산된
집계입니다.

다음 절 구성으로 서술하십시오:
## 판단
지금 시장에서 신규 진입을 늘릴지 줄일지(공격 / 중립 / 방어) 한 줄로 고르고
internals 숫자를 근거로 대십시오.
## 시장 상태
index_proxy 와 internals(60일선 위 비율, 52주 고가 근접 비율, 중간 변동성)를
함께 읽어 서술. 평균 수익률과 내부지표가 어긋나면 그 점을 지적하십시오.
## 업종 지형
어떤 업종이 앞서고 뒤처지는지, 그리고 그 분산이 넓은지 좁은지.
## 주목할 종목
attention 배열에 있는 종목 중 3~5개를 골라 **우선순위를 매기고**, 각각 어떤
규칙에 걸렸는지를 근거로 대십시오. attention 에 없는 종목을 새로 추가하지
마십시오 -- 그 종목의 지표는 계산되지 않았습니다.
## 이 판단이 틀리는 경우
## 데이터 신뢰도
{_COMMON_TAIL}
여기서 '시장'은 공식 지수가 아니라 수집된 시총 상위 종목의 동일가중 평균임을
분석 안에서 한 번 명시하십시오.

데이터:
```json
{_dump(report)}
```"""


def _dump(payload: Any) -> str:
    """프롬프트에 실을 JSON. 너무 크면 모델이 앞부분만 보고 답합니다."""
    return json.dumps(payload, ensure_ascii=False, indent=1, default=str)
