"""AI 분석 프롬프트.

이 파일의 설계 목표는 하나입니다: **모델이 숫자를 지어내지 못하게 하는 것.**

세 가지 장치를 씁니다.

  1. 모델에게 검색이나 기억을 요구하지 않습니다. 실적·뉴스·목표주가를 묻지
     않고, `app/reports.py` 가 계산한 숫자만 JSON 으로 넘긴 뒤 **그 안에서만**
     서술하게 합니다. 넘기지 않은 것은 "데이터에 없다"고 말하도록 지시합니다.

  2. 점 예측을 금지합니다. 이 앱 전체가 "내일 얼마"를 하지 않는다는 원칙 위에
     서 있는데, AI 서술만 예외로 두면 원칙이 무의미해집니다.

  3. 출력 형식을 고정합니다. 마지막 절은 항상 '반대 해석'과 '이 분석의 한계'
     입니다. 강세 서술만 남으면 사용자는 그것을 추천으로 읽습니다.

모델의 지식 시점(cutoff)은 알 수 없고 데이터는 오늘 것이므로, 기억에 의존한
서술은 그 자체로 틀릴 위험이 큽니다 -- 그래서 근거를 전부 프롬프트에 싣습니다.
"""

from __future__ import annotations

import json
from typing import Any

SYSTEM = """당신은 한국어로 답하는 주식 데이터 분석 보조자입니다.

절대 규칙:
1. 제공된 JSON 데이터에 있는 숫자만 사용하십시오. 실적, 뉴스, 공시, 목표주가,
   경쟁사 정보 등 데이터에 없는 것은 절대 지어내지 마십시오. 필요하면
   "이 앱의 데이터에는 없습니다"라고 쓰십시오.
2. 점 예측을 하지 마십시오. "내일 X원", "3개월 뒤 Y%" 같은 문장은 금지입니다.
   방향과 조건("~이 유지되면", "~을 밑돌면")으로 서술하십시오.
3. 매수/매도/보유 추천을 하지 마십시오. 당신의 역할은 데이터가 무엇을
   말하는지 서술하는 것이지 결정을 내리는 것이 아닙니다.
   분할 구간을 서술할 때도 마찬가지입니다 -- "여기서 사십시오"가 아니라
   "이 가격대는 과거 N회 반등한 지지 후보이며, 계획상 1회차 구간입니다"
   처럼 **구간이 무엇인지**를 서술하십시오.
4. 숫자를 인용할 때는 데이터의 값을 그대로 쓰십시오. 반올림은 허용되나
   없는 값을 추정하지 마십시오. null 은 "측정 불가"입니다.
5. 기술적 지표의 한계를 함께 쓰십시오. 특히 지지/저항과 이동평균 교차는
   학술 근거가 약하며 후행 신호입니다.

출력은 마크다운이며, 마지막 두 절은 반드시 다음이어야 합니다:
## 반대 해석
## 이 분석의 한계
"""

_COMMON_TAIL = """
분량은 400~700자 정도로 압축하십시오. 표는 쓰지 말고 짧은 문단과 불릿으로
쓰십시오. 데이터의 caveats 배열에 담긴 한계는 '이 분석의 한계' 절에 반영하십시오.
"""

# 종목 분석에는 회차별 서술이 들어가므로 위 분량으로는 눌립니다. 분량을 강하게
# 줄이면 모델은 가장 긴 절(분할 구간)부터 잘라내고, 그러면 요구한 3회차가
# 사라집니다.
_STOCK_TAIL = """
분량은 900~1,400자 정도로 쓰십시오. 표는 쓰지 말고 짧은 문단과 불릿으로
쓰십시오. 데이터의 caveats 배열에 담긴 한계는 '이 분석의 한계' 절에 반영하고,
분할 구간의 caveat 도 빠뜨리지 마십시오.
"""


def stock_prompt(report: dict[str, Any], forecast: dict | None = None) -> str:
    label = report.get("name") or report.get("ticker")
    body = {"stock": report}
    if forecast:
        body["forecast"] = forecast
    return f"""아래는 {report.get("market")} 시장 종목 **{label}
({report.get("ticker")})** 의 계산된 지표입니다.

다음 절 구성으로 서술하십시오:
## 지금 상태
현재 추세·모멘텀·변동성을 숫자와 함께 요약.
## 무엇이 눈에 띄는가
데이터에서 특이한 점(상대강도, 거래대금, 지지/저항 근접 등).
## 무엇을 지켜봐야 하는가
어떤 수치가 어떻게 바뀌면 해석이 달라지는지. 조건문으로만.
## 분할 대응 구간
데이터의 `ladder` 를 **그대로** 읽어 서술하십시오. 규칙:
- 매수 구간과 매도 구간을 **각각 최소 3회차**까지 회차별로 쓰십시오.
  회차마다 가격, 현재가 대비 거리, 비중, 그 회차까지 채웠을 때의 누적
  평균단가를 함께 적습니다. 숫자는 `ladder` 에 있는 값을 쓰고 직접
  계산하지 마십시오.
- 각 회차의 근거를 밝히십시오. `basis` 가 `level` 이면 지지/저항 클러스터
  (터치 `touches` 회)이고, `volatility` 면 **지지선이 모자라 ATR 등간격으로
  채운 구간**입니다 -- 후자는 반드시 그렇게 명시하십시오. 둘을 같은 것처럼
  쓰면 안 됩니다.
- `invalidation` 가격을 언급하고, 그 선이 깨지면 이 구간들의 근거가 무엇을
  잃는지 쓰십시오.
- 마지막에 한 문장으로: 분할은 진입가의 분산을 줄일 뿐 기대수익을 높이지
  않으며, 하락이 이어지면 더 많은 금액이 물린다는 점.
비중 방식은 `equal`(균등) 기준으로 서술하되, `pyramid`(뒤가중 -- 매수는 더 싼
회차, 매도는 더 비싼 회차에 더 싣는 방식)와 평균단가가
어떻게 달라지는지 한 줄로 비교하십시오. 어느 쪽이 낫다고 말하지 마십시오.
## 반대 해석
## 이 분석의 한계
{_STOCK_TAIL}
데이터:
```json
{_dump(body)}
```"""


def sector_prompt(report: dict[str, Any]) -> str:
    return f"""아래는 {report.get("market")} 시장 **{report.get("sector")}** 업종의
계산된 집계입니다.

다음 절 구성으로 서술하십시오:
## 업종 현황
수익률·상대강도·breadth 를 함께 읽어 서술. breadth 가 0.5 미만이면 소수 종목이
끌어올린 것이므로 반드시 그렇게 쓰십시오.
## 업종 내부 분화
leaders 와 laggards 의 격차가 무엇을 뜻하는지.
## 지켜볼 지점
## 반대 해석
## 이 분석의 한계
{_COMMON_TAIL}
데이터:
```json
{_dump(report)}
```"""


def market_prompt(report: dict[str, Any]) -> str:
    market_kr = "한국" if report.get("market") == "KR" else "미국"
    return f"""아래는 **{market_kr} 시장** 전체(수집된 유니버스 동일가중)의 계산된
집계입니다.

다음 절 구성으로 서술하십시오:
## 시장 상태
index_proxy 와 internals(60일선 위 비율, 52주 고가 근접 비율, 중간 변동성)를
함께 읽어 서술. 평균 수익률과 내부지표가 어긋나면 그 점을 지적하십시오.
## 업종 지형
어떤 업종이 앞서고 뒤처지는지, 그리고 그 분산이 넓은지 좁은지.
## 주목할 종목
attention 배열에 있는 종목 중 3~5개를 골라, **각각 어떤 규칙에 걸렸는지**를
근거로 왜 관찰 대상인지 쓰십시오. 매수 추천이 아니라 관찰 후보임을 명시하고,
attention 에 없는 종목을 새로 추가하지 마십시오.
## 반대 해석
## 이 분석의 한계
{_COMMON_TAIL}
여기서 '시장'은 공식 지수가 아니라 수집된 시총 상위 종목의 동일가중 평균임을
분석 안에서 한 번 명시하십시오.

데이터:
```json
{_dump(report)}
```"""


def _dump(payload: Any) -> str:
    """프롬프트에 실을 JSON. 너무 크면 모델이 앞부분만 보고 답합니다."""
    return json.dumps(payload, ensure_ascii=False, indent=1, default=str)
